#!/usr/bin/env python3
"""Writes Sources/SELPHYCP1500Print/ColourTargetData.swift from validation/references/colour_targets.json,
so that the app and the Python tools use the same reference values.

    python3 scripts/make-targets.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "validation/references/colour_targets.json").read_text())


def swift_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = ["// Generated by scripts/make-targets.py from validation/references/colour_targets.json: do not edit.",
         "// Reference CIELab values (D50, 2 degree observer) of the colour targets; provenance in `source`.",
         "", "extension ReferenceSet {", "    static let builtIn: [ReferenceSet] = ["]
for s in data["sets"]:
    lines.append("        ReferenceSet(")
    lines.append(f"            id: {swift_string(s['id'])}, model: .{s['target']}, edition: {swift_string(s['edition'])},")
    lines.append(f"            note: {swift_string(s['note'])},")
    lines.append(f"            source: {swift_string(s['source'])},")
    lines.append("            patches: [")
    for p in s["patches"]:
        l, a, b = p["lab"]
        lines.append(f"                ReferencePatch(name: {swift_string(p['name'])}, l: {l}, a: {a}, b: {b}),")
    lines.append("            ]")
    lines.append("        ),")
lines += ["    ]", "}", ""]
(ROOT / "Sources/SELPHYCP1500Print/ColourTargetData.swift").write_text("\n".join(lines))
print("written", len(data["sets"]), "sets")
